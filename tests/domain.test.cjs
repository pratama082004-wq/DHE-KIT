const assert=require('node:assert/strict');
const D=require('../domain.js');
const plan={start:'2026-10-05',weeks:12,days:[1,3,5],time:'08:00',minutes:45};
assert.equal(D.validDate('2026-02-30'),false);
assert.equal(D.validDate('2024-02-29'),true);
assert.equal(D.addDays('2026-12-31',1),'2027-01-01');
assert.equal(D.monday('2026-10-18'),'2026-10-12');
assert.deepEqual(D.plannedDates(plan,'2026-10-05','2026-10-11'),['2026-10-05','2026-10-07','2026-10-09']);
assert.equal(D.plannedDates(plan).length,36);
assert.equal(D.plannedDates(plan,'2026-10-01','2026-10-04').length,0);
const sessions=[{date:'2026-10-05',minutes:45,status:'Selesai',intensity:'Ringan'},{date:'2026-10-05',minutes:45,status:'Selesai',intensity:'Ringan'},{date:'2026-10-07',minutes:20,status:'Sebagian',intensity:'Ringan'},{date:'2026-10-09',minutes:30,status:'Selesai',intensity:'Sedang'},{date:'2026-10-10',minutes:45,status:'Selesai',intensity:'Ringan'}];
const s=D.stats(sessions,[],plan,'2026-10-05','2026-10-11');
assert.equal(s.attendance,67,'Duplicate sessions and off-schedule days must not inflate attendance');
assert.equal(s.adherence,33,'Short and partial sessions must not count as adherence');
assert.equal(D.stats([{date:'2026-10-05',minutes:45}],[],plan,'2026-10-05','2026-10-05').adherence,0,'Legacy records without intensity cannot prove adherence');
assert.equal(s.minutes,165);
assert.equal(D.stats([],[],plan,'2026-10-01','2026-10-04').attendance,null);
assert.equal(D.screen(120,80).blocked,false);
assert.equal(D.screen(160,100).blocked,false);
assert.equal(D.screen(161,80).blocked,true);
assert.equal(D.screen(120,101).blocked,true);
assert.equal(D.screen(180,80).level,'danger');
assert.equal(D.screen(150,110).level,'danger');
assert.equal(D.screen(120,80,true).level,'danger');
assert.equal(D.screen(120,80,false,true).blocked,true);
assert.equal(D.screen(0,0).blocked,true);
assert.equal(D.screen(70,80).blocked,true);
const cal=D.calendar(plan);
assert.equal((cal.match(/BEGIN:VEVENT/g)||[]).length,36);
assert.match(cal,/DTSTART:20261005T080000\r\nDTEND:20261005T084500/);
assert.match(cal,/TRIGGER:-PT15M/);
assert.match(cal,/END:VCALENDAR\r\n$/);
const csv=D.csv([['=HYPERLINK("bad")','normal','a,b','a"b','line\nbreak']]);
assert.match(csv,/"'=HYPERLINK/,'Protect spreadsheet formula injection');
assert.match(csv,/"a,b"/);
assert.match(csv,/"a""b"/);
console.log('PASS: dates, schedule boundaries, attendance, adherence, screening, ICS, CSV');
